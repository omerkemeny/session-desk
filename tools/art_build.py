"""Writes web/src/art.generated.js from web/art/*.txt so the page loads the art without a fetch; --check exits 1 when the file is stale."""
import argparse
import glob
import json
import os
import sys

WEB = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "web")
OUT = os.path.join(WEB, "src", "art.generated.js")
HEAD = "// Generated by tools/art_build.py from web/art/*.txt. Do not edit; edit the .txt files and run: python3 tools/art_build.py\n"


def build():
    """The module text: each art file's source, keyed by file name."""
    files = sorted(glob.glob(os.path.join(WEB, "art", "*.txt")))
    body = ",\n".join(f"  {json.dumps(os.path.basename(f))}: {json.dumps(open(f, encoding='utf-8').read())}" for f in files)
    return HEAD + "/** @type {Record<string, string>} */\nexport const ART_TEXT = {\n" + body + "\n};\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="only report whether the generated file is current")
    text = build()
    current = open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else None
    if ap.parse_args().check:
        print("art.generated.js is current" if current == text else "art.generated.js is stale: run python3 tools/art_build.py")
        sys.exit(0 if current == text else 1)
    if current != text:
        with open(OUT, "w", encoding="utf-8") as fh:
            fh.write(text)
    print("wrote " + os.path.relpath(OUT))


if __name__ == "__main__":
    main()
